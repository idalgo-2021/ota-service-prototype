export const translateAdmin = (text: string, lang: CatalogLanguage) => {
  if (lang !== 'en') {
    return text;
  }
  const exact = COPY[text];
  if (exact) {
    return exact;
  }
  if (text.startsWith('Бронь ')) {
    return `Booking ${text.slice('Бронь '.length)}`;
  }
  if (text.startsWith('бронь ')) {
    return `booking ${text.slice('бронь '.length)}`;
  }
  if (text.startsWith('Заказ ')) {
    return `Order ${text.slice('Заказ '.length)}`;
  }
  if (text.startsWith('заказ ')) {
    return `order ${text.slice('заказ '.length)}`;
  }
  if (text.startsWith('Изменить: ')) {
    return `Edit: ${text.slice('Изменить: '.length)}`;
  }
  return text;
};

export const translateResourceConfig = (
  config: ResourceConfig,
  lang: CatalogLanguage
): ResourceConfig => {
  if (lang !== 'en') {
    return config;
  }
  return {
    ...config,
    label: translateAdmin(config.label, lang),
    title: translateAdmin(config.title, lang),
    createLabel: config.createLabel && translateAdmin(config.createLabel, lang),
    editActionLabel: config.editActionLabel && translateAdmin(config.editActionLabel, lang),
    emptyText: translateAdmin(config.emptyText, lang),
    filters: config.filters?.map((filter) => ({
      ...filter,
      label: translateAdmin(filter.label, lang),
      options: Array.isArray(filter.options)
        ? filter.options.map((option) => ({ ...option, label: translateAdmin(option.label, lang) }))
        : filter.options,
    })),
    columns: config.columns.map((column) => ({
      ...column,
      title: translateAdmin(column.title, lang),
    })),
    fields: config.fields?.map((field) => ({
      ...field,
      label: translateAdmin(field.label, lang),
      hint: field.hint && translateAdmin(field.hint, lang),
      placeholder: field.placeholder && translateAdmin(field.placeholder, lang),
      options: Array.isArray(field.options)
        ? field.options.map((option) => ({ ...option, label: translateAdmin(option.label, lang) }))
        : field.options,
    })),
    actions: config.actions?.map((action) => ({
      ...action,
      label: translateAdmin(action.label, lang),
      reason: action.reason && {
        ...action.reason,
        title: translateAdmin(action.reason.title, lang),
        confirmLabel: translateAdmin(action.reason.confirmLabel, lang),
      },
    })),
    details: config.details && {
      ...config.details,
      label: translateAdmin(config.details.label, lang),
    },
  };
};

const AdminLanguageContext = createContext<CatalogLanguage>('ru');

export const AdminLanguageProvider = ({
  lang,
  children,
}: {
  lang: CatalogLanguage;
  children: ReactNode;
}) => <AdminLanguageContext.Provider value={lang}>{children}</AdminLanguageContext.Provider>;

export const useAdminLanguage = () => useContext(AdminLanguageContext);
